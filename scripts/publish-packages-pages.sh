#!/usr/bin/env bash
# Build the Orion Belt package site (https://pkgs.orion-belt.dev, served by
# GitHub Pages from orion-belt-dev/packages) from a release's files.
#
# Layout:
#   /                          the .deb and .rpm packages (rpm: RPM_ARCHS),
#                              install.sh, install.ps1, keys, VERSION, TAG,
#                              CONTAINERS
#   /dists/stable/...          apt: deb [signed-by=...] <site> stable main
#   /repodata/...              dnf, yum, zypper: <site>/orion-belt.repo
#   /apk/<arch>/               apk: <site>/apk in /etc/apk/repositories
#   /archlinux/<arch>/         pacman: Server = <site>/archlinux/$arch
#   /scoop/orion-belt.json     scoop install <site>/scoop/orion-belt.json
#
# The agent's packages keep the flat names install scripts generated by
# earlier servers download (orion-belt-agent_<ver>_amd64.deb, ...).
#
# Sources (first match wins):
#   1. ORION_DIST / dist/       (after goreleaser)
#   2. --from-release           the GitHub release ORION_PKG_TAG (default: latest)
#
# Signing (required with ORION_REQUIRE_SIGN=1):
#   ORION_GPG_KEY        fingerprint of a secret key in the keyring: apt
#                        InRelease, rpm repomd.xml, pacman databases
#   ORION_APK_PRIVKEY    RSA private key (PEM) for the APKINDEX signatures;
#                        its public half is published as apk/orion-belt.rsa.pub
#
# apk and pacman indexes are built in alpine and archlinux containers
# (docker or podman, ORION_CONTAINER_RUNTIME).
#
# Usage:
#   ./scripts/publish-packages-pages.sh                  # build packages-site/
#   ./scripts/publish-packages-pages.sh --from-release
#   ./scripts/publish-packages-pages.sh --push           # publish to orion-belt-dev/packages gh-pages
#
# Push auth (--push):
#   ORION_PACKAGES_TOKEN or PACKAGES_TOKEN  HTTPS token with contents:write on the packages repo
#   PACKAGES_DEPLOY_KEY                     SSH deploy key (write) on the packages repo
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST="${ORION_DIST:-$ROOT/dist}"
OUT="${ORION_PACKAGES_OUT:-$ROOT/packages-site}"
REPO_SLUG="${ORION_PACKAGES_REPO:-orion-belt-dev/packages}"
SOURCE_REPO="${ORION_SOURCE_REPO:-orion-belt-dev/orion-belt}"
DOMAIN="${ORION_PACKAGES_DOMAIN:-pkgs.orion-belt.dev}"
SITE_URL="${ORION_PACKAGES_URL:-https://$DOMAIN}"
KEY="${ORION_GPG_KEY:-}"
REQUIRE_SIGN="${ORION_REQUIRE_SIGN:-0}"
# GitHub Pages refuses sites over 1 GB; stop well before that.
MAX_SITE_MB="${ORION_MAX_SITE_MB:-950}"
# RPM architectures the site hosts: the ones RPM distributions ship. The
# release has the others; install.sh falls back to them.
RPM_ARCHS="${ORION_RPM_ARCHS:-x86_64 aarch64 ppc64le s390x riscv64}"
FROM_RELEASE=0
PUSH=0

for arg in "$@"; do
  case "$arg" in
    --from-release) FROM_RELEASE=1 ;;
    --push) PUSH=1 ;;
    -h|--help) sed -n '2,45p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

die() { echo "error: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null || die "missing: $1"; }
need curl
need python3
need gzip

RUNTIME="${ORION_CONTAINER_RUNTIME:-}"
if [[ -z "$RUNTIME" ]]; then
  if command -v docker >/dev/null; then RUNTIME=docker; elif command -v podman >/dev/null; then RUNTIME=podman; fi
fi
# Pinned by digest, like every image the project uses.
ALPINE_IMAGE="${ORION_ALPINE_IMAGE:-alpine:3.24@sha256:71e9b7bae160ba167fa17414401b94cbcdaf3c32feeab9298bd794a2a0614c35}"
ARCH_IMAGE="${ORION_ARCHLINUX_IMAGE:-archlinux:base@sha256:52dfbd5afb23a220d5ee92dafcb4c788d96c026ed04179890c23adef4c897fa0}"
FEDORA_IMAGE="${ORION_FEDORA_IMAGE:-fedora:44@sha256:43b29f65a41eb9c35e1cd5323e3bdf3b655c2357a9f4f1ff2f9c2798e5045d80}"

sign_ok=0
if [[ -n "$KEY" ]] && command -v gpg >/dev/null && gpg --list-secret-keys "$KEY" >/dev/null 2>&1; then
  sign_ok=1
fi
if [[ "$REQUIRE_SIGN" == "1" ]]; then
  [[ "$sign_ok" -eq 1 ]] || die "ORION_REQUIRE_SIGN=1 but ORION_GPG_KEY is not a usable secret key"
fi

resolve_tag() {
  if [[ -n "${ORION_PKG_TAG:-}" ]]; then echo "$ORION_PKG_TAG"; return; fi
  local tag
  tag="$(git -C "$ROOT" describe --tags --abbrev=0 2>/dev/null || true)"
  if [[ -n "$tag" && "$FROM_RELEASE" != "1" ]]; then echo "$tag"; return; fi
  curl -fsSL "https://api.github.com/repos/$SOURCE_REPO/releases/latest" \
    | python3 -c 'import sys,json; print(json.load(sys.stdin)["tag_name"])'
}

TAG="$(resolve_tag)"
VER="${TAG#v}"
RELEASE_BASE="https://github.com/$SOURCE_REPO/releases/download/$TAG"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Collect the release files into $SRC.
SRC="$DIST"
if [[ "$FROM_RELEASE" == "1" || ! -d "$DIST" ]]; then
  SRC="$WORK/release"
  mkdir -p "$SRC"
  echo "==> Downloading $TAG release files"
  curl -fsSL "https://api.github.com/repos/$SOURCE_REPO/releases/tags/$TAG" \
    | python3 -c '
import sys, json
for a in json.load(sys.stdin)["assets"]:
    n = a["name"]
    if n.endswith((".deb", ".rpm", ".apk", ".pkg.tar.zst", ".sig", ".tar.gz", ".zip")) or n in ("checksums.txt", "install.sh", "install.ps1"):
        print(a["browser_download_url"])
' | while read -r url; do
    curl -fsSL -o "$SRC/${url##*/}" "$url"
  done
fi

shopt -s nullglob
debs=("$SRC"/*.deb)
rpms=("$SRC"/*.rpm)
apks=("$SRC"/*.apk)
zsts=("$SRC"/*.pkg.tar.zst)
((${#debs[@]})) || die "no .deb packages in $SRC"

echo "==> Building $OUT for $TAG"
rm -rf "$OUT"
mkdir -p "$OUT"

# ── Keys ──────────────────────────────────────────────────────────────
if [[ "$sign_ok" -eq 1 ]]; then
  fpr="$(gpg --with-colons --fingerprint "$KEY" | awk -F: '/^fpr/ {print $10; exit}')"
  gpg --armor --export "$KEY" >"$OUT/orion-belt.asc"
  gpg --export "$KEY" >"$OUT/orion-belt.gpg"
  echo "$fpr" >"$OUT/orion-belt.fingerprint"
elif [[ -f "$ROOT/packaging/keys/orion-belt.asc" ]]; then
  cp "$ROOT/packaging/keys/orion-belt.asc" "$ROOT/packaging/keys/orion-belt.gpg" "$ROOT/packaging/keys/orion-belt.fingerprint" "$OUT/"
fi

gpg_sign() { # gpg_sign MODE FILE OUT   MODE: clear | detach | detach-armor
  [[ "$sign_ok" -eq 1 ]] || return 0
  case $1 in
    clear) gpg --batch --yes --local-user "$KEY" --clearsign -o "$3" "$2" ;;
    detach) gpg --batch --yes --local-user "$KEY" --detach-sign -o "$3" "$2" ;;
    detach-armor) gpg --batch --yes --local-user "$KEY" --armor --detach-sign -o "$3" "$2" ;;
  esac
}

# ── apt (site root) ───────────────────────────────────────────────────
need dpkg-scanpackages
need apt-ftparchive
cp -f "${debs[@]}" "$OUT/"
deb_archs="$(for d in "${debs[@]}"; do dpkg-deb -f "$d" Architecture; done | sort -u | tr '\n' ' ')"
for arch in $deb_archs; do
  dir="$OUT/dists/stable/main/binary-$arch"
  mkdir -p "$dir"
  (cd "$OUT" && dpkg-scanpackages --multiversion --arch "$arch" . /dev/null 2>/dev/null) >"$dir/Packages"
  gzip -9nk "$dir/Packages"
done
(
  cd "$OUT"
  apt-ftparchive \
    -o APT::FTPArchive::Release::Origin="Orion Belt" \
    -o APT::FTPArchive::Release::Label="Orion Belt" \
    -o APT::FTPArchive::Release::Suite=stable \
    -o APT::FTPArchive::Release::Codename=stable \
    -o APT::FTPArchive::Release::Components=main \
    -o APT::FTPArchive::Release::Architectures="${deb_archs% }" \
    release dists/stable >"$WORK/Release"
  mv "$WORK/Release" dists/stable/Release
)
gpg_sign clear "$OUT/dists/stable/Release" "$OUT/dists/stable/InRelease"
gpg_sign detach-armor "$OUT/dists/stable/Release" "$OUT/dists/stable/Release.gpg"
echo "  apt: ${#debs[@]} packages ($deb_archs)"

# ── rpm (site root, next to the apt pool) ─────────────────────────────
site_rpms=()
for f in "${rpms[@]}"; do
  a="${f%.rpm}"
  a="${a##*.}"
  [[ " $RPM_ARCHS " == *" $a "* ]] && site_rpms+=("$f")
done
if ((${#site_rpms[@]})); then
  cp -f "${site_rpms[@]}" "$OUT/"
  # Index only the .rpm files at the root (createrepo_c recurses).
  mkdir -p "$WORK/rpmlist"
  (cd "$OUT" && ls ./*.rpm) >"$WORK/rpmlist/pkglist"
  if command -v createrepo_c >/dev/null; then
    createrepo_c --quiet --pkglist "$WORK/rpmlist/pkglist" "$OUT"
  else
    [[ -n "$RUNTIME" ]] || die "createrepo_c, docker or podman is needed for the rpm metadata"
    "$RUNTIME" run --rm -v "$OUT:/repo" -v "$WORK/rpmlist:/list:ro" "$FEDORA_IMAGE" sh -euc '
      dnf -q -y install createrepo_c >/dev/null
      createrepo_c --quiet --pkglist /list/pkglist /repo
      chown -R '"$(id -u):$(id -g)"' /repo/repodata'
  fi
  gpg_sign detach-armor "$OUT/repodata/repomd.xml" "$OUT/repodata/repomd.xml.asc"
  repo_gpg=0
  [[ "$sign_ok" -eq 1 ]] && repo_gpg=1
  printf '%s\n' "[orion-belt]" "name=Orion Belt" "baseurl=$SITE_URL" "enabled=1" \
    "gpgcheck=$repo_gpg" "repo_gpgcheck=$repo_gpg" "gpgkey=$SITE_URL/orion-belt.asc" >"$OUT/orion-belt.repo"
  # install.sh uses the repository only for these.
  for a in $RPM_ARCHS; do echo "$a"; done >"$OUT/rpm-archs"
  echo "  rpm: ${#site_rpms[@]} packages ($RPM_ARCHS)"
fi

# ── apk (/apk/<arch>, built in an Alpine container) ───────────────────
if ((${#apks[@]})); then
  [[ -n "$RUNTIME" ]] || die "docker or podman is needed to index the apk packages"
  mkdir -p "$WORK/apk"
  for f in "${apks[@]}"; do
    # apk fetches <pkgname>-<pkgver>.apk from <repo>/<arch>/: names from
    # each package's .PKGINFO (an apk is concatenated gzip tar streams).
    read -r name ver arch < <(tar -xzOif "$f" .PKGINFO 2>/dev/null \
      | awk -F' = ' '$1=="pkgname"{n=$2} $1=="pkgver"{v=$2} $1=="arch"{a=$2} END{print n, v, a}')
    [[ -n "$name" && -n "$ver" && -n "$arch" ]] || die "cannot read .PKGINFO of $f"
    mkdir -p "$OUT/apk/$arch"
    cp -f "$f" "$OUT/apk/$arch/$name-$ver.apk"
  done
  pub=""
  if [[ -n "${ORION_APK_PRIVKEY:-}" ]]; then
    cp "$ORION_APK_PRIVKEY" "$WORK/apk/orion-belt.rsa"
    openssl rsa -in "$WORK/apk/orion-belt.rsa" -pubout -out "$OUT/apk/orion-belt.rsa.pub" 2>/dev/null
    cp "$OUT/apk/orion-belt.rsa.pub" "$WORK/apk/orion-belt.rsa.pub"
    pub=1
  elif [[ "$REQUIRE_SIGN" == "1" ]]; then
    echo "  warn: ORION_APK_PRIVKEY not set: apk index unsigned (install.sh then installs release files)" >&2
  fi
  "$RUNTIME" run --rm -v "$OUT/apk:/repo" -v "$WORK/apk:/keys:ro" -e SIGN="$pub" "$ALPINE_IMAGE" sh -euc '
    apk add --no-cache abuild >/dev/null
    for d in /repo/*/; do
      a=$(basename "$d")
      cd "$d"
      apk index --quiet --allow-untrusted --rewrite-arch "$a" -o APKINDEX.tar.gz ./*.apk
      if [ -n "$SIGN" ]; then abuild-sign -q -k /keys/orion-belt.rsa -p orion-belt.rsa.pub APKINDEX.tar.gz; fi
    done
    chown -R '"$(id -u):$(id -g)"' /repo'
  # Flat names for the agent install scripts of earlier servers.
  for f in "$SRC"/orion-belt-agent_*_x86_64.apk "$SRC"/orion-belt-agent_*_aarch64.apk; do cp -f "$f" "$OUT/"; done
  echo "  apk: ${#apks[@]} packages ($(cd "$OUT/apk" && ls -d */ | tr -d / | tr '\n' ' '))"
fi

# ── pacman (/archlinux/<arch>, built in an Arch container) ────────────
if ((${#zsts[@]})); then
  [[ -n "$RUNTIME" ]] || die "docker or podman is needed to index the pacman packages"
  # Architectures with an Arch Linux port that installs these.
  for f in "${zsts[@]}"; do
    b="$(basename "$f" .pkg.tar.zst)"
    arch="${b##*-}"
    case $arch in x86_64 | aarch64 | armv7h | i686) ;; *) continue ;; esac
    mkdir -p "$OUT/archlinux/$arch"
    cp -f "$f" "$OUT/archlinux/$arch/"
    [[ -f "$f.sig" ]] && cp -f "$f.sig" "$OUT/archlinux/$arch/"
  done
  "$RUNTIME" run --rm --platform linux/amd64 -v "$OUT/archlinux:/repo" "$ARCH_IMAGE" bash -euc '
    for d in /repo/*/; do
      cd "$d"
      repo-add --quiet orion-belt.db.tar.gz ./*.pkg.tar.zst
      # Pages serves no symlinks: real files under the names pacman fetches.
      for n in db files; do rm -f "orion-belt.$n"; cp "orion-belt.$n.tar.gz" "orion-belt.$n"; done
    done
    chown -R '"$(id -u):$(id -g)"' /repo'
  for db in "$OUT"/archlinux/*/orion-belt.db "$OUT"/archlinux/*/orion-belt.files; do
    gpg_sign detach "$db" "$db.sig"
  done
  echo "  pacman: $(cd "$OUT/archlinux" && ls -d */ | tr -d / | tr '\n' ' ')"
fi

# ── Installers, scoop ─────────────────────────────────────────────────
# Binary that install scripts of earlier servers fall back to (linux/amd64).
agz="$SRC/orion-belt-agent_${VER}_linux_amd64.tar.gz"
if [[ -f "$agz" ]]; then
  tar -xzf "$agz" -C "$WORK" orion-belt-agent
  install -m 0755 "$WORK/orion-belt-agent" "$OUT/orion-belt-agent"
fi
cp "$ROOT/scripts/install.sh" "$OUT/install.sh"
cp "$ROOT/packaging/windows/install.ps1" "$OUT/install.ps1"

if [[ -f "$SRC/checksums.txt" ]]; then
  mkdir -p "$OUT/scoop"
  python3 - "$SRC/checksums.txt" "$VER" "$RELEASE_BASE" >"$OUT/scoop/orion-belt.json" <<'PY'
import json, sys
sums = dict(reversed(l.split()) for l in open(sys.argv[1]) if l.strip())
ver, base = sys.argv[2], sys.argv[3]
arch = {}
for scoop_arch, go_arch in (("64bit", "amd64"), ("arm64", "arm64"), ("32bit", "386")):
    name = f"orion-belt_tools_{ver}_windows_{go_arch}.zip"
    if name in sums:
        arch[scoop_arch] = {"url": f"{base}/{name}", "hash": sums[name]}
json.dump({
    "version": ver,
    "description": "Orion Belt clients: osh, ocp, oadmin",
    "homepage": "https://orion-belt.dev",
    "license": "Apache-2.0 WITH Commons-Clause",
    "architecture": arch,
    "bin": ["osh.exe", "ocp.exe", "oadmin.exe"],
}, sys.stdout, indent=2)
PY
fi

# ── Site files ────────────────────────────────────────────────────────
printf '%s\n' "$VER" >"$OUT/VERSION"
printf '%s\n' "$TAG" >"$OUT/TAG"
printf '%s\n' "$DOMAIN" >"$OUT/CNAME"
touch "$OUT/.nojekyll"
SERVER_IMG="ghcr.io/orion-belt-dev/orion-belt-server"
AGENT_IMG="ghcr.io/orion-belt-dev/orion-belt-agent"
cat >"$OUT/CONTAINERS" <<EOF
# Orion Belt images on GitHub Container Registry (multi-arch).
#
#   docker pull ${SERVER_IMG}:${VER}
#   docker pull ${AGENT_IMG}:${VER}
#
${SERVER_IMG}:${VER}
${SERVER_IMG}:${TAG}
${SERVER_IMG}:latest
${AGENT_IMG}:${VER}
${AGENT_IMG}:${TAG}
${AGENT_IMG}:latest
EOF

python3 - "$OUT" "$TAG" "$SITE_URL" "$RELEASE_BASE" "$SRC" >"$OUT/index.html" <<'PY'
import html, os, sys
out, tag, site, rel, src = sys.argv[1:6]
ver = tag[1:]
fpr = ""
if os.path.exists(f"{out}/orion-belt.fingerprint"):
    fpr = open(f"{out}/orion-belt.fingerprint").read().strip()
def ls(d):
    p = os.path.join(out, d)
    return sorted(x for x in os.listdir(p) if os.path.isdir(os.path.join(p, x))) if os.path.isdir(p) else []
deb_archs = ls("dists/stable/main") and [a[len("binary-"):] for a in ls("dists/stable/main")]
clients = sorted(f for f in os.listdir(src) if f.startswith(f"orion-belt_tools_{ver}_") and (f.endswith(".tar.gz") or f.endswith(".zip")))
e = html.escape
rows = "\n".join(
    f'<tr><td>{e(f[len(f"orion-belt_tools_{ver}_"):].rsplit(".", 2 if f.endswith(".tar.gz") else 1)[0].replace("_", " / "))}</td>'
    f'<td><a href="{e(rel)}/{e(f)}">{e(f)}</a></td></tr>' for f in clients)
print(f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Orion Belt packages</title>
<style>
:root {{ --bg:#fff; --fg:#111; --muted:#555; --code:#f4f4f5; --link:#0b57d0; --line:#e4e4e7; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg:#0b0b0c; --fg:#e7e7ea; --muted:#a1a1aa; --code:#18181b; --link:#8ab4f8; --line:#27272a; }} }}
body {{ background:var(--bg); color:var(--fg); font:16px/1.55 ui-sans-serif,system-ui,sans-serif; max-width:56rem; margin:2rem auto; padding:0 1rem; }}
a {{ color:var(--link); }} h2 {{ margin-top:2rem; border-bottom:1px solid var(--line); padding-bottom:.25rem; }}
pre, code {{ background:var(--code); border-radius:6px; }} code {{ padding:.1em .35em; }}
pre {{ padding:.75rem 1rem; overflow-x:auto; }} p.muted {{ color:var(--muted); }}
table {{ border-collapse:collapse; width:100%; }} td {{ padding:.3rem .5rem; border-bottom:1px solid var(--line); vertical-align:top; }}
</style>
</head>
<body>
<h1>Orion Belt packages</h1>
<p>Signed package repositories for Orion Belt <strong>{e(tag)}</strong>: the server and agent for Linux, and the
<code>osh</code>, <code>ocp</code> and <code>oadmin</code> clients for Linux, macOS, Windows, the BSDs, illumos and Solaris.</p>
<p class="muted">Signing key: <a href="orion-belt.asc">orion-belt.asc</a>{f" — fingerprint <code>{e(fpr)}</code>" if fpr else ""}.
Release files: <a href="https://github.com/orion-belt-dev/orion-belt/releases/tag/{e(tag)}">GitHub release {e(tag)}</a>.</p>

<h2>Quick install</h2>
<pre>curl -fsSL {e(site)}/install.sh | sh                 # clients (Linux, macOS, BSD, illumos)
curl -fsSL {e(site)}/install.sh | sh -s -- agent      # agent (Linux)
curl -fsSL {e(site)}/install.sh | sh -s -- server     # server (Linux)</pre>
<pre>irm {e(site)}/install.ps1 | iex                       # clients (Windows)
scoop install {e(site)}/scoop/orion-belt.json         # clients (Windows, scoop)</pre>
<p class="muted">On Linux the installer adds the repository below for your package manager, so upgrades arrive with the system's.</p>

<h2>Debian, Ubuntu, Raspberry Pi OS</h2>
<p class="muted">Architectures: {e(" ".join(deb_archs) if deb_archs else "-")}</p>
<pre>sudo curl -fsSLo /usr/share/keyrings/orion-belt.gpg {e(site)}/orion-belt.gpg
echo "deb [signed-by=/usr/share/keyrings/orion-belt.gpg] {e(site)} stable main" | sudo tee /etc/apt/sources.list.d/orion-belt.list
sudo apt-get update && sudo apt-get install orion-belt-agent   # or orion-belt, orion-belt-tools</pre>

<h2>Fedora, RHEL, Rocky, Alma, Amazon Linux, openSUSE</h2>
<pre>sudo curl -fsSLo /etc/yum.repos.d/orion-belt.repo {e(site)}/orion-belt.repo
sudo dnf install orion-belt-agent        # or yum install

sudo zypper addrepo {e(site)}/orion-belt.repo   # openSUSE / SLES
sudo zypper install orion-belt-agent</pre>

<h2>Alpine</h2>
<p class="muted">Architectures: {e(" ".join(ls("apk")) or "-")}</p>
<pre>sudo wget -O /etc/apk/keys/orion-belt.rsa.pub {e(site)}/apk/orion-belt.rsa.pub
echo "{e(site)}/apk" | sudo tee -a /etc/apk/repositories
sudo apk update && sudo apk add orion-belt-agent</pre>

<h2>Arch Linux, Arch Linux ARM</h2>
<p class="muted">Architectures: {e(" ".join(ls("archlinux")) or "-")}</p>
<pre>curl -fsSL {e(site)}/orion-belt.asc | sudo pacman-key --add -
sudo pacman-key --lsign-key {e(fpr or "&lt;fingerprint&gt;")}
printf '[orion-belt]\\nServer = {e(site)}/archlinux/$arch\\n' | sudo tee -a /etc/pacman.conf
sudo pacman -Sy orion-belt-agent</pre>

<h2>Services</h2>
<p>The server and agent packages install their service for systemd, OpenRC, runit or SysV init, but do not start it until it is configured:
<code>/usr/lib/orion-belt/orion-belt-agent-service setup</code> (or <code>orion-belt-server-service</code>) enables and starts it on any of them.</p>

<h2>Containers</h2>
<pre>docker pull ghcr.io/orion-belt-dev/orion-belt-server:{e(ver)}
docker pull ghcr.io/orion-belt-dev/orion-belt-agent:{e(ver)}</pre>

<h2>Client downloads</h2>
<table>{rows}</table>
</body>
</html>""")
PY

# ── Checks ────────────────────────────────────────────────────────────
size_mb=$(du -sm "$OUT" | cut -f1)
echo "==> $(find "$OUT" -type f | wc -l | tr -d ' ') files, ${size_mb} MB in $OUT"
((size_mb <= MAX_SITE_MB)) || die "site is ${size_mb} MB, over ORION_MAX_SITE_MB=${MAX_SITE_MB} (GitHub Pages limit: 1 GB)"
((size_mb * 100 <= MAX_SITE_MB * 85)) || echo "warn: site is ${size_mb} MB, within 15% of ORION_MAX_SITE_MB=${MAX_SITE_MB}" >&2
big="$(find "$OUT" -type f -size +95M)"
[[ -z "$big" ]] || die "files over GitHub's 100 MB limit: $big"

if [[ "$PUSH" != "1" ]]; then
  echo "Done. To publish: $0 --push"
  exit 0
fi

# ── Publish ───────────────────────────────────────────────────────────
need git
TOKEN="${ORION_PACKAGES_TOKEN:-${PACKAGES_TOKEN:-}}"
DEPLOY_KEY="${PACKAGES_DEPLOY_KEY:-}"
if [[ -n "$TOKEN" ]]; then
  CLONE_URL="https://x-access-token:${TOKEN}@github.com/${REPO_SLUG}.git"
elif [[ -n "$DEPLOY_KEY" ]]; then
  eval "$(ssh-agent -s)" >/dev/null
  echo "$DEPLOY_KEY" | tr -d '\r' | ssh-add - >/dev/null
  mkdir -p ~/.ssh && chmod 700 ~/.ssh
  ssh-keyscan github.com >>~/.ssh/known_hosts 2>/dev/null || true
  CLONE_URL="git@github.com:${REPO_SLUG}.git"
else
  die "--push needs ORION_PACKAGES_TOKEN (or PACKAGES_TOKEN) or PACKAGES_DEPLOY_KEY with write access to $REPO_SLUG"
fi

# One commit, force-pushed: the site holds the latest release only, and old
# package files must not pile up in the repository's history.
git -C "$OUT" init -q -b gh-pages
git -C "$OUT" add -A
git -C "$OUT" -c user.name="${GIT_AUTHOR_NAME:-orion-belt-bot}" \
  -c user.email="${GIT_AUTHOR_EMAIL:-maintainers@orion-belt.dev}" \
  commit -q -m "Publish packages ${TAG}"
git -C "$OUT" push -q --force "$CLONE_URL" gh-pages
rm -rf "$OUT/.git"
echo "Published → ${SITE_URL}/"
